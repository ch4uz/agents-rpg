// Generator for assets/ui/thought-cloud-large.svg — rasterizes a balloon
// silhouette (a smooth round-top DOME ellipse + a rounded body rect) into the
// repo's rect-grid pixel-art SVG convention: outline = boundary cells, fill =
// interior, top-left shine band, bottom shade rows. Output is committed as a
// static SVG; regenerate with this script rather than hand-editing.
const W = 120, H = 66;

// Round top, the PIXEL-ART way: a flat top edge with TIGHT quarter-circle
// corners (radius ~ the small cloud's own curvature). A wide shallow ellipse
// was tried first and looked wrong — its near-crown steps become long 1px
// runs that read as aliasing wobble, not drawn pixels. Tight corners give
// short, deliberate steps, exactly like thought-cloud.svg's silhouette.
const body = { x0: 2, y0: 2, x1: 117, y1: 63, rTop: 15, rBottom: 9 };

const inRoundedRect = (x, y) => {
  if (x < body.x0 || x > body.x1 || y < body.y0 || y > body.y1) return false;
  const r = y < (body.y0 + body.y1) / 2 ? body.rTop : body.rBottom;
  const rx = Math.max(body.x0 + r - x, x - (body.x1 - r), 0);
  const ry = Math.max(body.y0 + r - y, y - (body.y1 - r), 0);
  return rx * rx + ry * ry <= r * r;
};
const inside = (x, y) => x >= 0 && x < W && y >= 0 && y < H && inRoundedRect(x, y);

// Classify cells.
const kind = Array.from({ length: H }, () => new Array(W).fill(null));
for (let y = 0; y < H; y++) {
  for (let x = 0; x < W; x++) {
    if (!inside(x, y)) continue;
    const boundary = !inside(x - 1, y) || !inside(x + 1, y) || !inside(x, y - 1) || !inside(x, y + 1);
    kind[y][x] = boundary ? 'o' : 'f';
  }
}
// Shade: the bottom 2 interior rows (cells whose 1-2 cells below are outline/outside).
for (let y = 0; y < H; y++) {
  for (let x = 0; x < W; x++) {
    if (kind[y][x] !== 'f') continue;
    const below1 = kind[y + 1]?.[x];
    const below2 = kind[y + 2]?.[x];
    if (below1 !== 'f' || below2 !== 'f') kind[y][x] = 'd';
  }
}
// Shine: just inside the top-left corner arc + a short run under the top
// edge — same treatment as the small cloud's upper-left highlight.
const cTL = { cx: body.x0 + body.rTop, cy: body.y0 + body.rTop };
for (let y = 0; y < H; y++) {
  for (let x = 0; x < W; x++) {
    if (kind[y][x] !== 'f') continue;
    if (x < cTL.cx && y < cTL.cy) {
      const d2 = (x - cTL.cx) ** 2 + (y - cTL.cy) ** 2;
      if (d2 >= (body.rTop - 3) ** 2 && d2 <= (body.rTop - 1) ** 2) kind[y][x] = 's';
    }
    if (y >= body.y0 + 1 && y <= body.y0 + 2 && x >= cTL.cx && x <= cTL.cx + 16) kind[y][x] = 's';
  }
}

// Emit per-row runs per color.
const runs = { o: [], f: [], s: [], d: [] };
for (let y = 0; y < H; y++) {
  let x = 0;
  while (x < W) {
    const k = kind[y][x];
    if (!k) { x++; continue; }
    let x2 = x;
    while (x2 + 1 < W && kind[y][x2 + 1] === k) x2++;
    runs[k].push(`<rect x="${x}" y="${y}" width="${x2 - x + 1}" height="1"/>`);
    x = x2 + 1;
  }
}
const g = (color, items) => `  <g fill="${color}">\n    ${items.join('\n    ')}\n  </g>`;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" shape-rendering="crispEdges">
  <!-- Pixel-art thought cloud, EXPANDED reading panel (120x66 grid at 2x =
       240x132px). Same silhouette family + palette as thought-cloud.svg
       (flat top with tight pixel-rounded corners, dark ink outline, parchment body, top-left shine, bottom
       shade) so the hover state reads as the SAME cloud grown larger.
       GENERATED by rasterizing a rounded rect (rTop 15 / rBottom 9) —
       regenerate with bin/gen-thought-cloud.mjs rather than hand-editing. -->
${g('#2a2421', runs.o)}
${g('#f4ecd6', runs.f)}
${g('#fdf6e3', runs.s)}
${g('#d9ccab', runs.d)}
</svg>
`;
import { writeFileSync } from 'node:fs';
writeFileSync(new URL('../assets/ui/thought-cloud-large.svg', import.meta.url), svg);
console.log('rects:', runs.o.length + runs.f.length + runs.s.length + runs.d.length);
